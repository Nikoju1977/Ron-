'use strict';
const assert=require('node:assert/strict');
require('../ron-autonomy.js');
const A=globalThis.RONAutonomy;
const t=Date.parse('2026-10-25T12:00:00Z');
const m=A.mind(null,t);
const basic={now:t,mind:m,enabled:true,paused:false,hasMission:true,
  visible:true,engineReady:true,needsKey:false,interval:120000};
let d=A.inspect(basic);
assert.equal(d.mode,'ready','First mission should be eligible without waiting indefinitely');
assert.equal(A.inspect({...basic,enabled:false}).mode,'disabled');
assert.equal(A.inspect({...basic,paused:true}).mode,'paused');
assert.equal(A.inspect({...basic,hasMission:false}).mode,'idle');
assert.equal(A.inspect({...basic,visible:false}).mode,'suspended','Do not pretend to run when the app is hidden');
assert.equal(A.inspect({...basic,engineReady:false}).mode,'blocked');
assert.equal(A.inspect({...basic,needsKey:true}).mode,'approval','Automatic paid/cloud runs are disallowed');
assert.equal(A.inspect({...basic,mind:{...m,cycles:24}}).mode,'budget','Budget limits unattended agent calls');
assert.equal(A.inspect({...basic,cooldownUntil:t+75000}).mode,'cooldown','Honor cooldowns');
d=A.inspect({...basic,mind:{...m,lastAttemptAt:t-30000}});
assert.equal(d.mode,'scheduled');assert(d.delay>=89999&&d.delay<=90001);
d=A.inspect({...basic,mind:{...m,lastAttemptAt:t-121000}});
assert.equal(d.mode,'ready','Resume after a due interval without replaying missed cycles');
d=A.inspect({...basic,mind:{...m,lastAttemptAt:t-121000,failures:2}});
assert.equal(d.mode,'scheduled','Error backoff prevents loops');
assert.equal(A.mind({...m,day:'2026-10-24',cycles:19,failures:5},t).cycles,0,'Daily counters reset');
const mission={status:'active',progress:40,nextStep:'Vérifier la source',stalls:2};
const repeated=A.observe(mission,{status:'active',progress:40,next_step:'Vérifier la source'});
assert.equal(repeated.status,'waiting','Stop hallucinated busy loops');
assert(repeated.question.length>0);
const progress=A.observe(mission,{status:'active',progress:70,next_step:'Comparer les relevés',self_check:'Progression non vérifiée',uncertainty:'Sources à vérifier'});
assert.equal(progress.status,'active');
assert.equal(progress.progress,70);
assert.equal(progress.stalls,0);
assert.equal(progress.uncertainty,'Sources à vérifier');
assert.equal(A.observe(mission,{status:'waiting',needs_user:true,question:'Accord ?'}).question,'Accord ?');
console.log(JSON.stringify({passed:true,suite:'autonomie-operationnelle',checks:16,paidAutoCalls:0}));
